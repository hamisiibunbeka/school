<?php

namespace App\Http\Controllers\Reports;

use App\Http\Controllers\Controller;
use App\Reports\Report;
use App\Reports\ReportRegistry;
use Illuminate\Http\Request;
use Inertia\Inertia;
use Inertia\Response;
use Symfony\Component\HttpFoundation\StreamedResponse;

/**
 * Reports & business intelligence (SRS 4.23): catalogue, generic viewer and
 * audited CSV export. Each report is a small class under App\Reports.
 */
class ReportController extends Controller
{
    /** Maximum rows sent to the browser; the CSV export is never truncated. */
    private const VIEW_LIMIT = 5000;

    public function __construct(private readonly ReportRegistry $registry) {}

    public function index(Request $request): Response
    {
        $catalogue = $this->registry->catalogue($request->user());

        return Inertia::render('reports/index', [
            'categories' => $catalogue,
            'total' => array_sum(array_map(fn ($c) => count($c['reports']), $catalogue)),
        ]);
    }

    public function show(Request $request, string $key): Response
    {
        $report = $this->resolve($request, $key);
        $filters = $report->resolveFilters($request->query());
        $result = $report->run($filters);

        $truncated = count($result['rows'] ?? []) > self::VIEW_LIMIT;
        if ($truncated) {
            $result['rows'] = array_slice($result['rows'], 0, self::VIEW_LIMIT);
        }

        return Inertia::render('reports/show', [
            'report' => $report->meta(),
            'category' => ReportRegistry::CATEGORIES[$report->category()][0] ?? $report->category(),
            'definitions' => $report->filters(),
            'filters' => (object) $filters,
            'result' => [
                'columns' => $result['columns'] ?? [],
                'rows' => $result['rows'] ?? [],
                'totals' => $result['totals'] ?? null,
                'summary' => $result['summary'] ?? [],
                'chart' => $result['chart'] ?? null,
                'note' => $result['note'] ?? null,
                'truncated' => $truncated,
            ],
            'meta' => $this->metadata($request, $report, $filters),
        ]);
    }

    public function export(Request $request, string $key): StreamedResponse
    {
        $report = $this->resolve($request, $key);
        $filters = $report->resolveFilters($request->query());
        $result = $report->run($filters);
        $meta = $this->metadata($request, $report, $filters);

        $this->audit('exported', null, "Exported report: {$report->title()} (".count($result['rows'] ?? []).' rows)', 'reports', null, ['report' => $report->key(), 'filters' => array_filter($filters, fn ($v) => $v !== '')]);

        $columns = $result['columns'] ?? [];

        return response()->streamDownload(function () use ($report, $result, $columns, $meta) {
            $out = fopen('php://output', 'w');
            fwrite($out, "\xEF\xBB\xBF"); // UTF-8 BOM so Excel renders names correctly
            fputcsv($out, [$meta['school'] ?? ''], ',', '"', '');
            fputcsv($out, [$report->title()], ',', '"', '');
            fputcsv($out, ['Reporting period', $meta['period']], ',', '"', '');
            foreach ($meta['filters'] as $f) {
                fputcsv($out, ['Filter: '.$f['label'], $f['value']], ',', '"', '');
            }
            fputcsv($out, ['Generated at', $meta['generated_at']], ',', '"', '');
            fputcsv($out, ['Generated by', $meta['generated_by']], ',', '"', '');
            fputcsv($out, ['Currency', $meta['currency']], ',', '"', '');
            fputcsv($out, [], ',', '"', '');

            fputcsv($out, array_map(fn ($c) => $c['label'], $columns), ',', '"', '');
            foreach ($result['rows'] ?? [] as $row) {
                fputcsv($out, array_map(fn ($c) => $this->csvValue($row[$c['key']] ?? null), $columns), ',', '"', '');
            }
            if (! empty($result['totals'])) {
                fputcsv($out, array_map(fn ($c) => $this->csvValue($result['totals'][$c['key']] ?? null), $columns), ',', '"', '');
            }
            fclose($out);
        }, $report->key().'-'.now()->format('Ymd-His').'.csv', ['Content-Type' => 'text/csv; charset=UTF-8']);
    }

    private function resolve(Request $request, string $key): Report
    {
        $report = $this->registry->find($key);
        abort_if($report === null, 404);
        abort_unless($report->authorize($request->user()), 403);

        return $report;
    }

    /**
     * SRS 4.23: reports show period, filters, generation time, author and currency.
     *
     * @param  array<string, string>  $filters
     * @return array<string, mixed>
     */
    private function metadata(Request $request, Report $report, array $filters): array
    {
        $school = $this->tenancy()->school();

        return [
            'school' => $school?->name,
            'period' => $report->period($filters),
            'filters' => $report->describeFilters($filters),
            'generated_at' => now()->setTimezone($school?->timezone ?? 'Africa/Dar_es_Salaam')->format('d/m/Y H:i'),
            'generated_by' => $request->user()->name,
            'currency' => $school?->currency ?? 'TZS',
        ];
    }

    private function csvValue(mixed $value): string
    {
        if (is_bool($value)) {
            return $value ? 'Yes' : 'No';
        }
        if (is_array($value)) {
            return implode(', ', $value);
        }

        return (string) ($value ?? '');
    }
}
